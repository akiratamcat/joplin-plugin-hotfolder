// Extract _("...") strings from src/**/*.ts and write src/locales/hotfolder.pot
// Usage: npm run i18n:extract
// Then update each .po with e.g.: msgmerge -U src/locales/ja_JP.po src/locales/hotfolder.pot

const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const srcDir = path.join(root, "src");
const potFile = path.join(srcDir, "locales", "hotfolder.pot");

function listTs(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) return listTs(p);
    return e.name.endsWith(".ts") ? [p] : [];
  });
}

function extract() {
  const entries = new Map(); // msgid -> [references]
  const re = /(?<![\w$.])_\(\s*"((?:[^"\\]|\\.)*)"/g;
  for (const file of listTs(srcDir)) {
    const content = fs.readFileSync(file, "utf8");
    let m;
    while ((m = re.exec(content)) !== null) {
      const msgid = JSON.parse('"' + m[1] + '"');
      const line = content.slice(0, m.index).split("\n").length;
      const ref = path.relative(root, file).replace(/\\/g, "/") + ":" + line;
      if (!entries.has(msgid)) entries.set(msgid, []);
      entries.get(msgid).push(ref);
    }
  }
  return entries;
}

function poEscape(s) {
  return s
    .replace(/\\/g, "\\\\")
    .replace(/"/g, '\\"')
    .replace(/\n/g, "\\n")
    .replace(/\t/g, "\\t");
}

function buildPot(entries) {
  const out = [
    "# Translation template for Joplin Plugin Hotfolder i18n",
    "# This file is generated by scripts/i18n-extract.js. Do not edit manually.",
    'msgid ""',
    'msgstr ""',
    '"Project-Id-Version: joplin-plugin-hotfolder-i18n\\n"',
    '"MIME-Version: 1.0\\n"',
    '"Content-Type: text/plain; charset=UTF-8\\n"',
    '"Content-Transfer-Encoding: 8bit\\n"',
    "",
  ];
  for (const [msgid, refs] of entries) {
    out.push("#: " + refs.join(" "));
    if (msgid.includes("%s")) out.push("#, c-format");
    out.push('msgid "' + poEscape(msgid) + '"');
    out.push('msgstr ""');
    out.push("");
  }
  return out.join("\n");
}

if (require.main === module) {
  const entries = extract();
  fs.writeFileSync(potFile, buildPot(entries), "utf8");
  console.log(
    `Wrote ${entries.size} messages to ${path.relative(root, potFile)}`
  );
}

module.exports = { extract, buildPot, poEscape };
